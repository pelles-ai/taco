#!/usr/bin/env node
/**
 * gen-changelog.js — copy ../CHANGELOG.md into docs/changelog.md with
 * Docusaurus frontmatter and a few light tweaks so it renders well in the
 * sidebar and search index.
 *
 * Runs automatically before `npm run build` and `npm run start`
 * via the `prebuild` / `prestart` package.json hooks.
 */

const fs = require('node:fs');
const path = require('node:path');

const REPO_ROOT = path.resolve(__dirname, '..', '..');
const SOURCE = path.join(REPO_ROOT, 'CHANGELOG.md');
const TARGET = path.resolve(__dirname, '..', 'docs', 'changelog.md');

const FRONTMATTER = `---
title: Changelog
description: Every notable change to the TACO SDK, generated from the canonical CHANGELOG.md at the repo root.
sidebar_position: 6
---

import Admonition from '@theme/Admonition';

:::info Generated
This page is copied from [\`CHANGELOG.md\`](https://github.com/pelles-ai/taco/blob/main/CHANGELOG.md) at the repo root by [\`website/scripts/gen-changelog.js\`](https://github.com/pelles-ai/taco/blob/main/website/scripts/gen-changelog.js). Edit the source CHANGELOG and re-run; do not edit this file by hand.
:::

`;

function generate() {
  if (!fs.existsSync(SOURCE)) {
    console.error(`[gen-changelog] CHANGELOG.md not found at ${SOURCE}`);
    process.exit(1);
  }

  const raw = fs.readFileSync(SOURCE, 'utf8');

  // The source starts with `# Changelog` — drop it because we add an h1 via
  // frontmatter's title. Keep everything else verbatim.
  let body = raw.replace(/^#\s+Changelog\s*\n+/m, '');

  // Light pass: render `## [Unreleased]` slightly more prominently than the
  // numeric versions — but keep the Markdown shape intact so anchors stay
  // stable (e.g. `[Unreleased]` heading still hashes to #unreleased).
  // We avoid heavier rewrites; the source is the canonical truth.

  const output = FRONTMATTER + body.trim() + '\n';
  fs.mkdirSync(path.dirname(TARGET), {recursive: true});
  fs.writeFileSync(TARGET, output);
  console.log(`[gen-changelog] wrote ${path.relative(REPO_ROOT, TARGET)}`);
}

generate();
